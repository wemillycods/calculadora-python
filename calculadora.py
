print("minha calculadora")
print("vamos calcular")

while True:
    n1 = input("digite o primeiro número: ")
    n2 = input("digite o segundo número: ")

    n1 = int(n1)
    n2 = int(n2)

    print("escolha a operação:")
    print("1 = soma")
    print("2 = subtração")
    print("3 = multiplicação")
    print("4 = divisão")

    escolha = input("digite o número da operação: ")

    soma = n1 + n2
    subtração = n1 - n2
    divisão = n1 / n2
    multiplicação = n1 * n2

    if escolha == "1":
        print("esse é o resultado da soma:", soma)
    elif escolha == "2":
        print("esse é o resultado da subtração:", subtração)
    elif escolha == "3":
        print("esse é o resultado da multiplicação:", multiplicação)
    elif escolha == "4":
        print("esse é o resultado da divisão:", divisão)
    else:
        print("opção inválida!")

    de_novo = input("Calcular de novo? (s/n): ")
    if de_novo == "n":
        print("Até logo!")
        break
